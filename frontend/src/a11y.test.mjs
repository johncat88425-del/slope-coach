function luminance(hex){const rgb=hex.slice(1).match(/.{2}/g).map(v=>parseInt(v,16)/255).map(v=>v<=.04045?v/12.92:((v+.055)/1.055)**2.4);return rgb[0]*.2126+rgb[1]*.7152+rgb[2]*.0722}
function contrast(a,b){const x=luminance(a.length===4?'#'+a.slice(1).split('').map(c=>c+c).join(''):a),y=luminance(b.length===4?'#'+b.slice(1).split('').map(c=>c+c).join(''):b);return (Math.max(x,y)+.05)/(Math.min(x,y)+.05)}
test('text tokens and verdict banners meet 4.5:1 contrast, including disabled controls',async()=>{
 const css=await readFile(new URL('./style.css',import.meta.url),'utf8');
 const token=Object.fromEntries([...css.matchAll(/--color-([\w-]+):(#[\da-f]+)/g)].map(([,key,value])=>[key,value]));
 for(const bg of [token.page,token.surface,token['disabled-bg']])for(const fg of [token.text,token.muted,token.eyebrow])assert.ok(contrast(fg,bg)>=4.5,`${fg} on ${bg}`);
 for(const verdict of ['consistent','inconsistent','insufficient_data']){
  const bg=css.match(new RegExp('\\.verdict-'+verdict+'\\{background:(#[\\da-f]+)'))?.[1];assert.ok(bg);assert.ok(contrast(token.page,bg)>=4.5,verdict);
 }
 assert.ok(contrast(token.focus,token.surface)>=4.5);assert.ok(contrast(token.focus,token.page)>=4.5);
 assert.doesNotMatch(css,/(?:button:disabled|fieldset:disabled)\{[^}]*opacity:\.[0-9]/);
 assert.match(css,/:focus-visible\s*\{[^}]*var\(--color-focus\)/);
});
test('result focus targets are labelled by their own verdict even when several results are on screen',()=>{
 const audit={audit_id:'a11y',assumed_model:'free_flight',verdict:'insufficient_data',t_start:0,t_end:1,camera_static:true,numbers:{},points:[],ghost_points:[],events:[],reasons:['example reason'],limits:[],track_source:'sam',nearest_body:null,headline:{source:'model',text:'Unchanged title'},explanation:{source:'model',text:'Original explanation 0.123456789'}};
 const html=render(h(Fragment,null,h(AuditResult,{audit,replay:true,autoFocus:true}),h(AuditResult,{audit:{...audit,audit_id:'second'},replay:true})));
 const labels=[...html.matchAll(/data-testid="audit-result"[^>]*aria-labelledby="([^"]+)"/g)].map(m=>m[1]);
 assert.equal(labels.length,2);assert.notEqual(labels[0],labels[1]);
 for(const id of labels)assert.ok(html.includes(`id="${id}" data-testid="audit-verdict"`));
 assert.equal((html.match(/tabindex="-1" data-testid="audit-result"/g)||[]).length,2);
 assert.match(html,/Written by Muse Spark/);assert.match(html,/Generated by Muse Spark/);assert.match(html,/Tracked by SAM 3.1/);assert.match(html,/Original explanation 0.123456789/);
});
test('explanation badges distinguish model and template in both languages and do not invent missing sources',()=>{
 assert.equal(render(h(ExplanationSource,{explanation:null})), '');
 for(const lang of ['en','zh'])for(const source of ['model','template']){
  const html=render(h(LanguageProvider,{value:lang},h(ExplanationSource,{explanation:{source,text:'unchanged'}})));
  assert.match(html,/data-testid="explanation-source"/);
  assert.match(html,source==='model'?/Muse Spark/:lang==='en'?/no model/:/未使用模型/);
  if(source==='template')assert.doesNotMatch(html,/Muse Spark/);
 }
});
